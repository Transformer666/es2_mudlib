//   的舊環，本該交付一個有膽識、肯為人奔走的後生，持環去開那封印、了結這段因果。
//   只是真正開封誅鬼的「四鬼招喚環」(d/chimei/npc/obj/ghost_ring)，繫於京畿聖木的
