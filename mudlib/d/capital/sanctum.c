//   一道守木一脈世代密封的石階﹐拾級而下﹐便是循聖木根脈鑿成、通往京畿地脈
//   的去路(神社地窖 cellar.c → 京畿地脈 → 聖木殘節密室 → 蜈穴)。此降地之路
//   唯已接第四章任務(quest/main_canon4 >= 1、即已自守木尊者處接得任務並領得
//   聖劍穿靈)者方得通行(由 valid_leave 就 down 方向把關)。故本室定義 valid_
//   leave 自訂函式﹐「不」replace_program（鏡 youhe.c 保留函式之做法）。

