// 為聖木殘根盤結封死的甬道遂轟然崩開——循甬道(in)而入﹐便是這方深嵌地脈最底、巨
// 蜈蟄伏三百年的蜈穴。那蝕聖木之節、致悔天鬼邪念外溢的巨蜈(npc/giant_centipede)
// 便盤踞於此。
