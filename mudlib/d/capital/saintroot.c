//
// 門禁/replace_program：本室既定義 valid_leave(就 in 方向把關蜈穴)﹐故「不」
//   replace_program（鏡 youhe.c/saintroot 同類做法——保留函式）。本室聖木節須持穿
//   靈方斫得斷、巨蜈尚在穴中未出﹐故此密室本身設 no_fight（戰場在蜈穴 wuxue.c）。

