//   槍→地氣塔頂」﹔並 jingang-zarn.c L19「金屋內丹提屬性」、tower_base.c/jiangyun.c
//   所述「須以聖木殘根、金屋內丹煉就炎日箭、太陽槍」之 lore）：
//   京畿神社神龕上那尊日神化身的太陽鳥﹐納了少俠所獻的大環丹這味丹引﹐振翅引
//   下一縷澄澈日華﹐將那丹引溫養、熔鑄而成的一枚內丹。丹成於日神化身之力﹐通
//   體流轉著金屋藏嬌般的暖芒﹐是這地靈一路承先啟後的中繼聖物——少俠須持它﹐連
//   同那聖木殘根﹐去煉就煉炎日箭、太陽槍﹐方能循四神之力層層引動﹐登臨地氣塔頂。
