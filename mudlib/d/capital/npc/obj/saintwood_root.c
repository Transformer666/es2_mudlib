//   生絞斷、攫入腹中的一段聖木深蟠地下的根脈。根上猶帶著巨蜈的涎毒與齒痕﹐然
//   其木質深處那一縷聖木所鍾的清正餘力卻仍未斷絕——巨蜈既誅、聖木節既斷﹐這截
//   殘根重歸守木尊者之手﹐溫養復甦﹐京畿地脈所養的聖木一脈﹐方有重續之望。守
//   木尊者言道：此殘根須帶回交與他﹐既是了結蜈蚣war的鐵證﹐亦是復甦聖木的根本。
