// 正史主線第五章「四鬼任務」的高潮之地。赤魈森林(d/chimei/forest.c)盡頭、那株亙古
// 的卯天樹之下，便是三百年前鎮封山林川原四鬼——赤魈(山鬼)、青蛛(林鬼)、濁魚(川鬼)、
// 旱魃(原鬼)——的封印之所在。三百年來鎮鬼封印鎮著四鬼沉睡；及至京畿聖木之節為巨蜈
// 蝕斷(第四章)，鎮鬼的封印一鬆，四鬼便在這封印之下蠢蠢欲動。少俠自漕幫耆宿江隕處
// 得四鬼招喚環(d/chimei/npc/obj/ghost_ring.c)，持環至此，於卯天樹下『用 環』(用 環 /
// use ring)，催動環上四道古篆，開那鎮鬼的封印，將四鬼盡數引出而一一誅之。
//
// 開封機制（do_use on 用 / use）——本室之核心：
//   * 玩家須身負第五章旗標(quest/main_canon5 == 1：已自江隕接環、四鬼未誅盡)且身上
//     帶著四鬼招喚環(present "ghost ring")，方開得這封印。
//   * 旗標非 1（未接任務，或四鬼已誅盡推進為 2 以上）：給合宜的中文訊息、不開封。
//   * 防重複召喚：本室若已有任一四鬼 present，告知封印已開、不再重召。
//   * 開封：戲劇性敘事後，逐一 clone 四鬼(chixiao/qingzhu/zhuoyu/hanba)move 入本室。
//     四鬼現身，由玩家自行 kill 之；四鬼之 die() 自理計數/推進/掉星光環——本室「不」
//     碰任何旗標。
//   * ⚠ 召喚過程中本室不可自毀(無 destruct/replace_program 於 do_use)——召喚邏輯須
//     完整執行。
//
// 門禁/replace_program：本室「不」定義 valid_leave（召喚已就 ring + 旗標雙重把關，
//   入口由赤魈森林 forest.c::valid_leave 就 down 方向把關 main_canon5>=1，鏡 youhe.c
//   做法），故本室乃純房間，可 replace_program(ROOM)。本室為四鬼戰場，「不」設
//   no_fight。

inherit ROOM;

int do_use(string arg);

