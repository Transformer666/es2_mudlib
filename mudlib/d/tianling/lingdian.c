// 正史主線第十一章「十三靈終局」的戰場。自人靈魂泉(soulwell.c)北面那道清光門徑拾
//   步而入，便是這座懸於萬仞雲海之上、應劫而生的十三靈殿。三百年前寒於氏一脈以一
//   身元神鎮鎖此山邪念，元神不甘潰散，化作十三道厲魂遊蕩殿中——是為「十三靈」(npc/
//   shisanling.c)。武者須先於人靈魂泉重凝大成、懸佩日月神薛，方堪臨此殿、了結這十三
//   道厲魂之患（入殿門禁已於 soulwell.c::valid_leave 就 north 把關）。
//
// 殿中生十三靈(set objects: shisanling x13)。此室為戰場——「不」設 no_fight，玩家自行
//   起釁誅靈。每誅一靈，由 shisanling.c::die() 為「殺者」之 quest/canon11_ling 計數
//   +1(0->13)；十三道厲魂盡滅、quest/canon11_ling >= 13 後，殿東(east)通往侮天鬼幽窟
//   (wugui_lair.c)的門徑方開——是為主線終局之路。
//
// 【lesson #11】本室定義 valid_leave 自訂函式，又 set objects 生怪——絕不可
//   replace_program(ROOM)（鏡 abyss.c/summit.c 戰場/把關房之做法）。

